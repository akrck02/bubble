package bubble

import (
	"bytes"
	"os"
	"regexp"
	"strings"
	"testing"
)

func TestTheTokensFileIsUpToDate(test *testing.T) {
	var generated bytes.Buffer
	if err := CSS(&generated, DefaultAccent); err != nil {
		test.Fatal(err)
	}
	saved, err := os.ReadFile("css/tokens.css")
	if err != nil {
		test.Fatalf("css/tokens.css: %v; make it with: go run ./cmd/bubble-css > css/tokens.css", err)
	}
	if !bytes.Equal(saved, generated.Bytes()) {
		test.Error("css/tokens.css is out of date; make it again with: go run ./cmd/bubble-css > css/tokens.css")
	}
}

func TestTheCSSFollowsTheSystemsDarkModeUnlessThePageSaysLight(test *testing.T) {
	var generated bytes.Buffer
	if err := CSS(&generated, DefaultAccent); err != nil {
		test.Fatal(err)
	}
	css := generated.String()
	for _, wanted := range []string{
		"@media (prefers-color-scheme: dark)",
		":root:not([data-mode=\"light\"])",
		":root[data-mode=\"dark\"]",
		"prefers-reduced-transparency",
	} {
		if !strings.Contains(css, wanted) {
			test.Errorf("the CSS has no %s", wanted)
		}
	}
}

func TestOnGlassNothingIsOpaqueUnlessTheSystemAsksForLessTransparency(test *testing.T) {
	var generated bytes.Buffer
	if err := CSS(&generated, DefaultAccent); err != nil {
		test.Fatal(err)
	}
	css := generated.String()
	for _, selector := range []string{":root[data-glass] {", ":root[data-glass][data-mode=\"dark\"] {"} {
		start := strings.Index(css, selector)
		if start == -1 {
			test.Fatalf("the CSS has no %s", selector)
		}
		block := css[start : start+strings.Index(css[start:], "}")]
		sunken := regexp.MustCompile(`--sunken: (#[0-9A-F]+);`).FindAllStringSubmatch(block, -1)
		last := sunken[len(sunken)-1][1]
		if len(last) != len("#RRGGBBAA") {
			test.Errorf("%s: the sunken colour %s is opaque", selector, last)
		}
	}
	if !strings.Contains(css, "--sunken: var(--accent-tint);") {
		test.Error("with less transparency, the sunken colour does not become solid")
	}
}
