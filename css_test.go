package bubble

import (
	"bytes"
	"os"
	"strings"
	"testing"
)

func TestTheTokensFileIsUpToDate(test *testing.T) {
	var generated bytes.Buffer
	if err := CSS(&generated, DefaultAccent); err != nil {
		test.Fatal(err)
	}
	saved, err := os.ReadFile("css/tokens.css")
	if err != nil {
		test.Fatalf("css/tokens.css: %v; make it with: go run ./cmd/bubble-css > css/tokens.css", err)
	}
	if !bytes.Equal(saved, generated.Bytes()) {
		test.Error("css/tokens.css is out of date; make it again with: go run ./cmd/bubble-css > css/tokens.css")
	}
}

func TestTheCSSFollowsTheSystemsDarkModeUnlessThePageSaysLight(test *testing.T) {
	var generated bytes.Buffer
	if err := CSS(&generated, DefaultAccent); err != nil {
		test.Fatal(err)
	}
	css := generated.String()
	for _, wanted := range []string{
		"@media (prefers-color-scheme: dark)",
		":root:not([data-mode=\"light\"])",
		":root[data-mode=\"dark\"]",
		"prefers-reduced-transparency",
	} {
		if !strings.Contains(css, wanted) {
			test.Errorf("the CSS has no %s", wanted)
		}
	}
}
