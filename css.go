package bubble

import (
	"fmt"
	"io"
	"strings"
)

// CSS writes the tokens of every style, mode and density as CSS custom properties, for one accent.
//
// The page chooses with attributes on <html>: data-style="material", data-mode="light" or "dark"
// (without it, the system's choice), data-density="compact" and data-glass. Paper, light and
// comfortable need no attribute.
func CSS(writer io.Writer, accent Color) error {
	var text strings.Builder
	text.WriteString("/* Bubble 4 tokens, generated by cmd/bubble-css for the accent " + accent.Hex() + ". Do not edit by hand. */\n")
	for _, block := range cssBlocks(accent) {
		if err := block.write(&text); err != nil {
			return err
		}
	}
	text.WriteString(solidGlassCSS)
	_, err := io.WriteString(writer, text.String())
	return err
}

type cssBlock struct {
	selector    string
	darkByMedia bool // also applies when the system asks for dark and the page does not say light
	options     Options
	parts       []func(Theme) []cssProperty
}

type cssProperty struct {
	name  string
	value string
}

func cssBlocks(accent Color) []cssBlock {
	options := func(style Style, mode Mode, density Density) Options {
		return Options{Style: style, Mode: mode, Density: density, Accent: accent}
	}
	every := []func(Theme) []cssProperty{colorProperties, shapeProperties, typeProperties, spaceProperties, motionProperties}
	colorsOnly := []func(Theme) []cssProperty{colorProperties}
	compactOnly := []func(Theme) []cssProperty{shapeProperties, typeProperties, spaceProperties}
	glassParts := []func(Theme) []cssProperty{colorProperties, glassProperties}
	glassy := func(options Options) Options {
		options.Glass = true
		return options
	}
	return []cssBlock{
		{selector: ":root", options: options(StylePaper, ModeLight, DensityComfortable), parts: every},
		{selector: ":root[data-mode=\"dark\"]", darkByMedia: true, options: options(StylePaper, ModeDark, DensityComfortable), parts: colorsOnly},
		{selector: ":root[data-style=\"material\"]", options: options(StyleMaterial, ModeLight, DensityComfortable), parts: []func(Theme) []cssProperty{colorProperties, shapeProperties}},
		{selector: ":root[data-style=\"material\"][data-mode=\"dark\"]", darkByMedia: true, options: options(StyleMaterial, ModeDark, DensityComfortable), parts: colorsOnly},
		{selector: ":root[data-density=\"compact\"]", options: options(StylePaper, ModeLight, DensityCompact), parts: compactOnly},
		{selector: ":root[data-style=\"material\"][data-density=\"compact\"]", options: options(StyleMaterial, ModeLight, DensityCompact), parts: []func(Theme) []cssProperty{shapeProperties}},
		// Glass comes last and weighs more, so it wins over the paper it reimagines.
		{selector: ":root[data-glass]", options: glassy(options(StylePaper, ModeLight, DensityComfortable)), parts: glassParts},
		{selector: ":root[data-glass][data-mode=\"dark\"]", darkByMedia: true, options: glassy(options(StylePaper, ModeDark, DensityComfortable)), parts: glassParts},
	}
}

func (block cssBlock) write(text *strings.Builder) error {
	theme, err := NewTheme(block.options)
	if err != nil {
		return err
	}
	var body strings.Builder
	for _, part := range block.parts {
		for _, property := range part(theme) {
			fmt.Fprintf(&body, "  --%s: %s;\n", property.name, property.value)
		}
	}
	fmt.Fprintf(text, "\n%s {\n%s}\n", block.selector, body.String())
	if block.darkByMedia {
		mediaSelector := strings.Replace(block.selector, "[data-mode=\"dark\"]", ":not([data-mode=\"light\"])", 1)
		fmt.Fprintf(text, "\n@media (prefers-color-scheme: dark) {\n  %s {\n%s  }\n}\n", mediaSelector, indent(body.String()))
	}
	return nil
}

func indent(text string) string {
	return strings.ReplaceAll(strings.TrimSuffix(text, "\n"), "\n", "\n  ") + "\n"
}

func colorProperties(theme Theme) []cssProperty {
	colors := theme.Colors
	return []cssProperty{
		{"background", colors.Background.Hex()}, {"surface", colors.Surface.Hex()}, {"sunken", colors.Sunken.Hex()},
		{"ink", colors.Ink.Hex()}, {"ink-soft", colors.InkSoft.Hex()}, {"ink-quiet", colors.InkQuiet.Hex()},
		{"line", colors.Line.Hex()}, {"control-line", colors.ControlLine.Hex()},
		{"accent", colors.Accent.Hex()}, {"on-accent", colors.OnAccent.Hex()}, {"accent-edge", colors.AccentEdge.Hex()},
		{"accent-side", colors.AccentSide.Hex()}, {"accent-ink", colors.AccentInk.Hex()}, {"accent-tint", colors.AccentTint.Hex()},
		{"positive", colors.Positive.Hex()}, {"warning", colors.Warning.Hex()}, {"danger", colors.Danger.Hex()},
		{"focus-ring", colors.FocusRing.Hex()}, {"selection", colors.Selection.Hex()},
		{"shadow", colors.Shadow.Hex()}, {"scrim", colors.Scrim.Hex()}, {"tile", colors.Tile.Hex()},
		{"color-scheme", string(theme.Options.Mode)},
	}
}

func pixels(value float64) string {
	return fmt.Sprintf("%gpx", value)
}

func shapeProperties(theme Theme) []cssProperty {
	shape := theme.Shape
	elevation := "none"
	if shape.Elevated {
		elevation = "0 1px 3px var(--shadow), 0 4px 12px var(--shadow)"
	}
	return []cssProperty{
		{"control-radius", pixels(shape.ControlRadius)}, {"button-radius", pixels(shape.ButtonRadius)},
		{"card-radius", pixels(shape.CardRadius)}, {"panel-radius", pixels(shape.PanelRadius)},
		{"floating-radius", pixels(shape.FloatingRadius)}, {"line-width", pixels(shape.LineWidth)},
		{"edge-width", pixels(shape.EdgeWidth)}, {"focus-width", pixels(shape.FocusWidth)},
		{"focus-offset", pixels(shape.FocusOffset)}, {"elevation", elevation},
	}
}

func typeProperties(theme Theme) []cssProperty {
	kind := theme.Type
	return []cssProperty{
		{"font", kind.Family}, {"font-monospace", kind.MonospaceFamily},
		{"text-small", pixels(kind.SmallSize)}, {"text-body", pixels(kind.BodySize)}, {"text-heading", pixels(kind.HeadingSize)},
		{"text-title", pixels(kind.TitleSize)}, {"text-display", pixels(kind.DisplaySize)}, {"icon-size", pixels(kind.IconSize)},
		{"line-height", fmt.Sprintf("%g", kind.LineHeight)},
	}
}

func spaceProperties(theme Theme) []cssProperty {
	space := theme.Space
	return []cssProperty{
		{"gap", pixels(space.Gap)}, {"padding", pixels(space.Padding)},
		{"control-height", pixels(space.ControlHeight)}, {"touch-target", pixels(space.TouchTarget)},
	}
}

func motionProperties(theme Theme) []cssProperty {
	motion := theme.Motion
	return []cssProperty{
		{"motion-fast", fmt.Sprintf("%gs", motion.Fast.Seconds())},
		{"motion-medium", fmt.Sprintf("%gs", motion.Medium.Seconds())},
		{"motion-slow", fmt.Sprintf("%gs", motion.Slow.Seconds())},
	}
}

// On glass nothing is opaque: what other styles sink (pills, keys, a hovered row) takes the
// raised pane instead, whose contrast is tested over the ground, the lights and any wallpaper.
// It comes after the colours, so it wins over their solid sunken.
func glassProperties(theme Theme) []cssProperty {
	glass := theme.Glass
	return []cssProperty{
		{"sunken", glass.Raised.Hex()},
		{"glass-pane", glass.Pane.Hex()}, {"glass-raised", glass.Raised.Hex()},
		{"glass-glow-one", glass.Glows[0].Hex()}, {"glass-glow-two", glass.Glows[1].Hex()},
		{"glass-veil", glass.Veil.Hex()}, {"glass-dimming", fmt.Sprintf("%g", glass.Dimming)},
		{"glass-blur", pixels(glass.Blur)},
	}
}

// When the system asks for less transparency, panels become their solid surface and stop blurring.
const solidGlassCSS = `
@media (prefers-reduced-transparency: reduce) {
  :root[data-glass] {
    --glass-pane: var(--surface);
    --glass-raised: var(--accent-tint);
    --sunken: var(--accent-tint);
    --glass-blur: 0px;
  }
}
`
